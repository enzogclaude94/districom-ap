BACKFILL = r"""
UPDATE commercial.documents AS d
SET customer_mapping_id = m.id
FROM commercial.document_types AS t, external_entity_mappings AS m, source_systems AS s
WHERE t.id = d.document_type_id
  AND t.document_class NOT IN ('EMPLOYEE_VOUCHER', 'INTERNAL_MOVEMENT')
  AND d.source_customer_code IS NOT NULL
  AND s.id = m.source_system_id
  AND s.code = 'STORE_SYS'
  AND m.entity_type = 'customer'
  AND m.namespace = 'customer'
  AND m.external_id = regexp_replace(btrim(d.source_customer_code), '\s+', ' ', 'g')
"""

# Sales always kept the id: only the lines imported while the code had no mapping are missing it.
ADOPT_SALE_LINES = r"""
UPDATE commercial.sale_lines AS l
SET customer_mapping_id = m.id
FROM external_entity_mappings AS m, source_systems AS s
WHERE l.customer_mapping_id IS NULL
  AND l.customer_id IS NULL
  AND s.id = m.source_system_id
  AND s.code = 'STORE_SYS'
  AND m.entity_type = 'customer'
  AND m.namespace = 'customer'
  AND m.external_id = regexp_replace(btrim(l.source_customer_code), '\s+', ' ', 'g')
"""

# The facts that just took a confirmed mapping get its customer (the re-resolution of `resolvers.apply`).
RESOLVE = r"""
UPDATE commercial.{table} AS f
SET customer_id = m.entity_id
FROM external_entity_mappings AS m
WHERE m.id = f.customer_mapping_id
  AND m.status = 'confirmed'
  AND f.customer_id IS NULL
"""

