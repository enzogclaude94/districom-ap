"""Requests and responses of the Cajas API. Amounts travel as decimal strings ("1500.00") or numbers."""

from datetime import date, datetime
from decimal import Decimal
from typing import Annotated
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, PlainSerializer

# Positive amount: the endpoint decides the direction.
Amount = Annotated[Decimal, Field(gt=0, max_digits=14, decimal_places=2)]
# Signed amount (adjustments): positive = surplus found, negative = shortage.
SignedAmount = Annotated[Decimal, Field(max_digits=14, decimal_places=2)]
Reason = Annotated[str, Field(min_length=1, max_length=500)]
# Responses always carry two decimals ("0.00", "1500.00"), whatever the sum produced.
Money = Annotated[Decimal, PlainSerializer(lambda v: str(v.quantize(Decimal("0.01"))), return_type=str)]


class OperationIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    # Generated by the client once per user action and resent on retries (ADR 008).
    client_request_id: UUID
    # Business date; today (business timezone) when omitted. Clients should send it so a retry is identical.
    business_date: date | None = None
    description: str | None = Field(default=None, max_length=500)


class CashTransferIn(OperationIn):
    from_account_id: int
    to_account_id: int
    amount: Amount


class BankDepositIn(OperationIn):
    cash_account_id: int
    bank_account_id: int
    amount: Amount


class BankWithdrawalIn(OperationIn):
    bank_account_id: int
    cash_account_id: int
    amount: Amount


class OpeningBalanceIn(OperationIn):
    account_id: int
    amount: Amount


class OwnerMovementIn(OperationIn):
    owner_account_id: int
    # Cash box or bank that receives (contribution) or pays (withdrawal) the money.
    account_id: int
    amount: Amount


class AdjustmentIn(OperationIn):
    account_id: int
    amount: SignedAmount
    description: Reason  # mandatory reason (D4)


class ReversalIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    client_request_id: UUID
    reason: Reason
    business_date: date | None = None


class OwnerAccountIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1, max_length=120)


class AccountOut(BaseModel):
    id: int
    code: str | None
    name: str
    kind: str
    allow_negative: bool
    active: bool
    balance: Money
    # «Banco en descubierto» (R4-2): a bank below zero, only ever by a cheque rejected after its crediting.
    overdrawn: bool
    overdrawn_label: str | None
    # What overdrew it (R4-3): the rejections after crediting in effect on this bank, newest first.
    overdraft_causes: list["OverdraftCauseOut"] = []


class OverdraftCauseOut(BaseModel):
    rejection_id: int
    cheque_id: int
    operation_id: int
    business_date: date
    amount: Money


class MovementOut(BaseModel):
    entry_id: int
    operation_id: int
    operation_type: str
    business_date: date
    description: str | None
    amount: Money
    created_by: int
    created_by_name: str
    created_at: datetime
    source_type: str | None
    source_id: int | None
    reverses_operation_id: int | None
    reversed_by_operation_id: int | None


class MovementPage(BaseModel):
    items: list[MovementOut]
    total: int


class EntryOut(BaseModel):
    account_id: int
    account_name: str
    account_kind: str
    amount: Money
    # The cheque a leg on a cheque account moves (R4-1); null on every other account.
    cheque_id: int | None = None


class OperationOut(BaseModel):
    id: int
    type: str
    business_date: date
    description: str | None
    created_by: int
    created_by_name: str
    created_at: datetime
    source_type: str | None
    source_id: int | None
    reverses_operation_id: int | None
    reversed_by_operation_id: int | None
    entries: list[EntryOut]
