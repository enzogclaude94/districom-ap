"""Requests and responses of the payments API (R6-1): a payment to a third party with one or several means,
its reversal and its descriptive correction, and the list of payments."""

from datetime import date, datetime
from typing import Annotated, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.modules.settlements.cash.schemas import Amount, Money, OperationOut, Reason
from app.modules.settlements.delivery.schemas import Text500

Concept = Literal["MERCHANDISE", "EXPENSE", "REFUND", "OTHER"]
# CHEQUE (R6-2): a cheque of the portfolio, delivered for its whole face amount.
Method = Literal["CASH", "TRANSFER", "CHEQUE"]
PaymentState = Literal["IN_EFFECT", "REVERSED"]
Reference = Annotated[str, Field(max_length=100)]
MAX_ITEMS = 20


class StrictIn(BaseModel):
    model_config = ConfigDict(extra="forbid")


class PaymentItemIn(StrictIn):
    method: Method
    # CASH: an active cash box; TRANSFER: an active bank account the user chose.
    account_id: int | None = None
    # CHEQUE: a cheque in the portfolio on the payment's date; `amount` must be its face amount.
    cheque_id: int | None = None
    amount: Amount
    reference: Reference | None = None


class PaymentIn(StrictIn):
    # Generated by the client once per user action and resent on retries (ADR 008).
    client_request_id: UUID
    # Today or a past day, never a future one; funds are checked from that day on.
    business_date: date
    third_party_id: int
    concept: Concept
    # EXPENSE only: an active category that is not fuel.
    expense_category_id: int | None = None
    # The total the user saw. Optional; when sent it must be exactly the sum of the items.
    amount: Amount | None = None
    reference: Reference | None = None
    # Required for OTHER.
    description: Text500 | None = None
    items: Annotated[list[PaymentItemIn], Field(max_length=MAX_ITEMS)]


class PaymentReversalIn(StrictIn):
    client_request_id: UUID
    reason: Reason
    # A payment with cheques is reversed only when EVERY cheque was physically recovered from the third
    # party: the ids of the cheques the user confirmed, one by one (R6-2). Empty for a payment without them.
    recovered_cheque_ids: Annotated[list[int], Field(max_length=MAX_ITEMS)] = []


class PaymentItemCorrection(StrictIn):
    id: int
    reference: Reference | None = None


class PaymentCorrectionIn(StrictIn):
    """An admin's descriptive correction, with a reason: only the fields sent change. Nothing financial is
    accepted here (any other field is refused): a wrong third party, date, concept, category, amount, item
    or account is a reversal and a new payment."""

    reason: Reason
    reference: Reference | None = None
    description: Text500 | None = None
    items: Annotated[list[PaymentItemCorrection], Field(max_length=MAX_ITEMS)] | None = None


class PaymentChequeOut(BaseModel):
    """The cheque of a CHEQUE item, as it is now (its state is derived: Entregado while the payment is in
    effect, back En cartera, or wherever it went, after a reversal with the cheque recovered)."""

    cheque_id: int
    kind: str
    payment_type: str
    cheque_number: str
    bank_name: str
    drawer_name: str
    delivered_by_name: str
    payable_from: date
    state: str
    state_label: str
    recovered_at: datetime | None
    recovered_by_name: str | None


class PaymentItemOut(BaseModel):
    id: int
    method: Method
    account_id: int | None
    account_name: str | None
    account_kind: str | None
    cheque_id: int | None
    cheque: PaymentChequeOut | None
    amount: Money
    reference: str | None


class PaymentOut(BaseModel):
    id: int
    state: PaymentState
    business_date: date
    third_party_id: int
    third_party_name: str
    third_party_tax_id_display: str | None
    third_party_active: bool
    concept: Concept
    expense_category_id: int | None
    expense_category_name: str | None
    # The technical account the counter-leg went to («Pagos por mercadería», «Gastos operativos»...).
    counter_account_name: str
    amount: Money
    reference: str | None
    description: str | None
    items: list[PaymentItemOut]
    operation_id: int | None
    reversal_operation_id: int | None
    created_by: int
    created_by_name: str
    created_at: datetime
    reversed_by_name: str | None
    reversed_at: datetime | None
    reversal_reason: str | None


class PaymentPage(BaseModel):
    items: list[PaymentOut]
    total: int
    # Sum of the payments in effect among the filtered ones (reversed ones never count).
    amount_in_effect: Money


class PaymentEventOut(BaseModel):
    id: int
    event_type: str
    occurred_at: datetime
    user_name: str | None
    before: dict[str, object] | None
    after: dict[str, object] | None


class PaymentDetail(PaymentOut):
    operation: OperationOut | None
    reversal: OperationOut | None
    history: list[PaymentEventOut]


class PaymentListQuery(BaseModel):
    third_party_id: int | None = None
    concept: Concept | None = None
    date_from: date | None = None
    date_to: date | None = None
    # Payments with an item from this cash box or bank account.
    account_id: int | None = None
    state: PaymentState | None = None
    limit: int = Field(default=50, ge=1, le=200)
    offset: int = Field(default=0, ge=0)
