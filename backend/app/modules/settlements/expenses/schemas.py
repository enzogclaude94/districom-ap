"""Requests and responses of the expenses API (R5-3): direct expenses, their reversal and correction, and
the list of every expense, direct or of a settlement."""

from datetime import date, datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.modules.settlements.cash.schemas import Amount, Money, OperationOut, Reason
from app.modules.settlements.delivery.schemas import FuelOut, Liters, Odometer, PricePerLiter, Text500

Origin = Literal["SETTLEMENT", "DIRECT"]
# IN_EFFECT; VOIDED (a settlement expense voided while its settlement was open); REVERSED (a direct expense
# undone by the reversal of its operation).
ExpenseState = Literal["IN_EFFECT", "VOIDED", "REVERSED"]


class StrictIn(BaseModel):
    model_config = ConfigDict(extra="forbid")


class DirectFuelIn(StrictIn):
    """Fuel load of a direct FUEL expense. There is no driver here, so who loaded it is always explicit."""

    vehicle_id: int
    # Required (`fuel_employee_required`): no default from a cash box.
    employee_id: int | None = None
    liters: Liters
    price_per_liter: PricePerLiter
    odometer_km: Odometer | None = None


class DirectExpenseIn(StrictIn):
    # Generated by the client once per user action and resent on retries (ADR 008).
    client_request_id: UUID
    # Today or a past day, never a future one; funds are checked from that day on.
    business_date: date
    category_id: int
    # The one cash box or bank account it was paid from.
    paid_from_account_id: int
    # Required for every category but FUEL, whose amount is computed from `fuel`.
    amount: Amount | None = None
    description: Text500 | None = None
    fuel: DirectFuelIn | None = None


class ExpenseReversalIn(StrictIn):
    client_request_id: UUID
    reason: Reason


class ExpenseCorrectionIn(StrictIn):
    """An admin's descriptive correction, with a reason: only the fields sent change. Nothing financial is
    accepted here (any other field is refused): a wrong amount, category, account, date or load is a
    reversal and a new expense."""

    reason: Reason
    description: Text500 | None = None
    odometer_km: Odometer | None = None


class ExpenseOut(BaseModel):
    id: int
    origin: Origin
    state: ExpenseState
    business_date: date
    category_id: int
    category_name: str
    category_code: str | None
    amount: Money
    description: str | None
    # SETTLEMENT only.
    settlement_id: int | None
    # DIRECT only.
    paid_from_account_id: int | None
    paid_from_account_name: str | None
    paid_from_account_kind: str | None
    operation_id: int | None
    reversal_operation_id: int | None
    fuel: FuelOut | None
    legacy_fuel_without_detail: bool
    created_by: int
    created_by_name: str
    created_at: datetime
    # Who voided or reversed it, when and why.
    ended_by_name: str | None
    ended_at: datetime | None
    end_reason: str | None


class ExpensePage(BaseModel):
    items: list[ExpenseOut]
    total: int


class ExpenseEventOut(BaseModel):
    id: int
    event_type: str
    occurred_at: datetime
    user_name: str | None
    before: dict[str, object] | None
    after: dict[str, object] | None


class ExpenseDetail(ExpenseOut):
    operation: OperationOut | None
    reversal: OperationOut | None
    history: list[ExpenseEventOut]


class ExpenseListQuery(BaseModel):
    origin: Origin | None = None
    category_id: int | None = None
    date_from: date | None = None
    date_to: date | None = None
    account_id: int | None = None
    state: ExpenseState | None = None
    limit: int = Field(default=50, ge=1, le=200)
    offset: int = Field(default=0, ge=0)
